const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, "zh-CN": zhCN };

function systemLanguage(): Language {
	return window.navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

function initialPreference(): LanguagePreference {
	const stored = window.localStorage.getItem(LANGUAGE_KEY);
	return stored === "zh-CN" || stored === "en" || stored === "system" ? stored : "system";
}

interface I18nContextValue {
	language: Language;
	preference: LanguagePreference;
	setPreference: (preference: LanguagePreference) => void;
	t: (key: TranslationKey, params?: Params) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }): React.JSX.Element {
	const [preference, setPreference] = useState<LanguagePreference>(initialPreference);
	const [deviceLanguage, setDeviceLanguage] = useState<Language>(systemLanguage);
	const language = preference === "system" ? deviceLanguage : preference;

	useEffect(() => {
		const onLanguageChange = (): void => setDeviceLanguage(systemLanguage());
		window.addEventListener("languagechange", onLanguageChange);
		return () => window.removeEventListener("languagechange", onLanguageChange);
	}, []);

	useEffect(() => {
		window.localStorage.setItem(LANGUAGE_KEY, preference);
		document.documentElement.lang = language;
	}, [language, preference]);

	const t = useCallback((key: TranslationKey, params?: Params): string => {
		let message = dictionaries[language][key] ?? dictionaries.en[key];
		for (const [name, value] of Object.entries(params ?? {})) {
			message = message.replaceAll(`{${name}}`, String(value));
		}
		return message;
	}, [language]);

	const value = useMemo(() => ({ language, preference, setPreference, t }), [language, preference, t]);
	return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
	const context = useContext(I18nContext);
	if (!context) throw new Error("useI18n must be used inside I18nProvider");
	return context;
}
